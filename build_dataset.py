def expand_conversations_to_sft_samples(conversations, system_prompt):
    """
    將完整多輪對話包裝成 SFTTrainer 直接相容的 messages 格式：
    {"messages": [{"role": "system", ...}, {"role": "user", ...}, {"role": "assistant", ...}, ...]}
    並且為了讓模型具備多輪能力，將每一輪歷史累積展開成逐步樣本。
    """
    samples = []
    for conv in conversations:
        history = [{"role": "system", "content": system_prompt}]
        for user_msg, bot_msg in conv:
            history.append({"role": "user", "content": user_msg})
            # 當前完整的對話歷史（包含最新 assistant 回應）
            current_turn = list(history)
            current_turn.append({"role": "assistant", "content": bot_msg})
            samples.append({"messages": current_turn})
            history.append({"role": "assistant", "content": bot_msg})
    return samples


def main():
    print("=" * 72)
    print("開始建構「情勒專家（情緒勒索大師）」多輪對話訓練資料集...")
    print("=" * 72)

    DATA_DIR.mkdir(parents=True, exist_ok=True)
    SFT_DIR.mkdir(parents=True, exist_ok=True)

    # 1. 儲存原始 conversations
    raw_chat_file = DATA_DIR / "chat.jsonl"
    with raw_chat_file.open("w", encoding="utf-8") as f:
        for conv in CONVERSATIONS:
            dialogue_messages = [{"role": "system", "content": SYSTEM_PROMPT}]
            for u, a in conv:
                dialogue_messages.append({"role": "user", "content": u})
                dialogue_messages.append({"role": "assistant", "content": a})
            f.write(json.dumps({"messages": dialogue_messages}, ensure_ascii=False) + "\n")
    print(f"完整情勒多輪對話已輸出至: {raw_chat_file.resolve()} (共 {len(CONVERSATIONS)} 段對話)")

    # 2. 先切分完整 conversation（避免 turn-level 洩漏）
    indices = list(range(len(CONVERSATIONS)))
    random.shuffle(indices)
    split_point = int(len(indices) * 0.85)
    train_indices = set(indices[:split_point])
    valid_indices = set(indices[split_point:])

    train_convs = [CONVERSATIONS[i] for i in train_indices]
    valid_convs = [CONVERSATIONS[i] for i in valid_indices]

    # 3. 展開為 SFT 樣本
    train_samples = expand_conversations_to_sft_samples(train_convs, SYSTEM_PROMPT)
    valid_samples = expand_conversations_to_sft_samples(valid_convs, SYSTEM_PROMPT)

    train_file = SFT_DIR / "train.jsonl"
    valid_file = SFT_DIR / "valid.jsonl"

    with train_file.open("w", encoding="utf-8") as f:
        for s in train_samples:
            f.write(json.dumps(s, ensure_ascii=False) + "\n")

    with valid_file.open("w", encoding="utf-8") as f:
        for s in valid_samples:
            f.write(json.dumps(s, ensure_ascii=False) + "\n")

    print("\n資料切分與展開完成：")
    print(f"  訓練集 (Train SFT 樣本): {len(train_samples)} 筆 -> {train_file.resolve()}")
    print(f"  驗證集 (Valid SFT 樣本): {len(valid_samples)} 筆 -> {valid_file.resolve()}")
    print("=" * 72)


if __name__ == "__main__":
    main()
